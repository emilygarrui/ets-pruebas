public class Main {
    public static void main(String[] args) {
        // Número hasta donde sumar
        int n = 10;
        
        // Fórmula para sumar los primeros n números
        int suma = (n * (n + 1)) / 2;
        
        // Mostrar el resultado
        System.out.println("La suma de los primeros " + n + " números es: " + suma);
    }
}